-- AULA360 PREMIUM · Backend de trabajos, materiales y entregas del aula virtual.
-- Los archivos quedan en buckets privados; descargas y entregas se autorizan desde PostgreSQL.

create table public.virtual_trabajos (
  id uuid primary key default gen_random_uuid(),
  docente_id uuid not null references public.profiles(id) on delete cascade,
  colegio_id bigint not null,
  titulo text not null check (char_length(btrim(titulo)) between 1 and 160),
  descripcion text check (descripcion is null or char_length(descripcion) <= 8000),
  tipo text not null check (tipo in ('trabajo','material')),
  fecha_limite timestamptz,
  max_descargas integer check (max_descargas is null or max_descargas between 1 and 100),
  max_entregas integer not null default 1 check (max_entregas between 1 and 10),
  max_mb integer not null default 10 check (max_mb between 1 and 25),
  tipos_permitidos text[] not null default array['pdf','doc','docx','jpg','png']::text[],
  permite_tarde boolean not null default false,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  constraint virtual_trabajos_tipos_validos check (
    cardinality(tipos_permitidos) between 1 and 10
    and tipos_permitidos <@ array['pdf','doc','docx','xls','xlsx','ppt','pptx','jpg','png','zip']::text[]
  )
);

create table public.virtual_trabajo_cursos (
  trabajo_id uuid not null references public.virtual_trabajos(id) on delete cascade,
  course_id uuid not null references public.courses(id) on delete cascade,
  docente_id uuid not null references public.profiles(id) on delete cascade,
  colegio_id bigint not null,
  created_at timestamptz not null default now(),
  primary key (trabajo_id, course_id)
);

create table public.virtual_archivos (
  id uuid primary key default gen_random_uuid(),
  trabajo_id uuid not null references public.virtual_trabajos(id) on delete cascade,
  docente_id uuid not null references public.profiles(id) on delete cascade,
  colegio_id bigint not null,
  path text not null unique,
  nombre text not null check (char_length(btrim(nombre)) between 1 and 255),
  tipo text not null check (tipo in ('pdf','doc','docx','xls','xlsx','ppt','pptx','jpg','png','zip')),
  size bigint not null check (size between 1 and 26214400),
  created_at timestamptz not null default now()
);

create table public.virtual_entregas (
  id uuid primary key default gen_random_uuid(),
  trabajo_id uuid not null references public.virtual_trabajos(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  docente_id uuid not null,
  colegio_id bigint not null,
  nombre text not null check (char_length(btrim(nombre)) between 1 and 255),
  size bigint not null check (size between 1 and 26214400),
  comentario text check (comentario is null or char_length(comentario) <= 2000),
  nota numeric(3,1) check (nota is null or nota between 0 and 5),
  retroalimentacion text check (retroalimentacion is null or char_length(retroalimentacion) <= 4000),
  created_at timestamptz not null default now(),
  path text not null unique,
  estado text not null default 'pendiente' check (estado in ('pendiente','enviada')),
  expires_at timestamptz not null default (now() + interval '30 minutes')
);

create table public.virtual_descargas (
  id bigint generated by default as identity primary key,
  archivo_id uuid not null references public.virtual_archivos(id) on delete cascade,
  trabajo_id uuid not null references public.virtual_trabajos(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  docente_id uuid not null references public.profiles(id) on delete cascade,
  colegio_id bigint not null,
  created_at timestamptz not null default now()
);

create index virtual_trabajos_docente_created_idx on public.virtual_trabajos(docente_id, created_at desc);
create index virtual_trabajos_school_created_idx on public.virtual_trabajos(colegio_id, created_at desc);
create index virtual_trabajo_cursos_course_idx on public.virtual_trabajo_cursos(course_id);
create index virtual_archivos_work_idx on public.virtual_archivos(trabajo_id);
create index virtual_entregas_work_state_idx on public.virtual_entregas(trabajo_id, estado, created_at desc);
create index virtual_entregas_user_work_idx on public.virtual_entregas(user_id, trabajo_id, estado);
create index virtual_descargas_file_user_idx on public.virtual_descargas(archivo_id, user_id);
create index virtual_descargas_work_idx on public.virtual_descargas(trabajo_id);

