create or replace function public.virtual_pedir_descarga(p_archivo uuid)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  u uuid := (select auth.uid());
  v_work public.virtual_trabajos%rowtype;
  v_path text;
  v_role text;
  v_course uuid;
  v_manager boolean := false;
  v_count integer := 0;
begin
  if u is null then raise exception 'Debes iniciar sesión'; end if;

  select t.* into v_work
  from public.virtual_trabajos t
  join public.virtual_archivos a on a.trabajo_id = t.id
  where a.id = p_archivo
  for update of t;
  if not found then raise exception 'El archivo no existe'; end if;

  select a.path into v_path from public.virtual_archivos a where a.id = p_archivo;
  v_manager := v_work.docente_id = u
    or public.aula360_is_admin()
    or (v_work.colegio_id = public.aula360_my_school()
        and public.aula360_my_role() in ('rector','coordinador'));

  if not v_manager then
    if v_work.activo is not true then raise exception 'Este material ya no está disponible'; end if;
    select p.role,p.course_id into v_role,v_course
    from public.profiles p where p.id = u;
    if v_role is distinct from 'est'
       or not exists (
         select 1 from public.virtual_trabajo_cursos tc
         where tc.trabajo_id = v_work.id and tc.course_id = v_course
       ) then
      raise exception 'No tienes acceso a este material';
    end if;

    if v_work.max_descargas is not null then
      select count(*) into v_count
      from public.virtual_descargas d
      where d.archivo_id = p_archivo and d.user_id = u;
      if v_count >= v_work.max_descargas then
        raise exception 'Ya alcanzaste el límite de descargas de este archivo';
      end if;
    end if;

    insert into public.virtual_descargas(archivo_id,trabajo_id,user_id,docente_id,colegio_id)
    values(p_archivo,v_work.id,u,v_work.docente_id,v_work.colegio_id);
  end if;

  return v_path;
end;
$$;

create or replace function public.virtual_pedir_entrega(p_trabajo uuid,p_nombre text,p_size bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  u uuid := (select auth.uid());
  v_work public.virtual_trabajos%rowtype;
  v_role text;
  v_course uuid;
  v_count integer := 0;
  v_match text[];
  v_ext text;
  v_path text;
  v_id uuid;
begin
  if u is null then raise exception 'Debes iniciar sesión'; end if;
  if coalesce(char_length(btrim(p_nombre)),0) not between 1 and 255 then
    raise exception 'Nombre de archivo inválido';
  end if;
  if p_size is null or p_size < 1 then raise exception 'El archivo está vacío o no es válido'; end if;

  select t.* into v_work
  from public.virtual_trabajos t
  where t.id = p_trabajo
  for update;
  if not found or v_work.tipo <> 'trabajo' or v_work.activo is not true then
    raise exception 'El trabajo no está disponible';
  end if;

  select p.role,p.course_id into v_role,v_course
  from public.profiles p where p.id = u;
  if v_role is distinct from 'est'
     or not exists (
       select 1 from public.virtual_trabajo_cursos tc
       where tc.trabajo_id = p_trabajo and tc.course_id = v_course
     ) then
    raise exception 'Este trabajo no está asignado a tu curso';
  end if;

  if v_work.fecha_limite is not null
     and now() > v_work.fecha_limite
     and v_work.permite_tarde is not true then
    raise exception 'La fecha límite ya pasó';
  end if;

  if p_size > v_work.max_mb::bigint * 1048576 then
    raise exception 'El archivo supera el límite de '||v_work.max_mb||' MB';
  end if;

  v_match := regexp_match(lower(btrim(p_nombre)), '\.([a-z0-9]{1,10})$');
  if v_match is null then raise exception 'El archivo debe tener una extensión permitida'; end if;
  v_ext := v_match[1];
  if not (v_ext = any(v_work.tipos_permitidos)) then
    raise exception 'El tipo de archivo .'||v_ext||' no está permitido';
  end if;

  select count(*) into v_count
  from public.virtual_entregas e
  where e.trabajo_id = p_trabajo
    and e.user_id = u
    and (
      e.estado = 'enviada'
      or (e.estado = 'pendiente' and e.expires_at > now())
    );
  if v_count >= v_work.max_entregas then
    raise exception 'Ya utilizaste todas las entregas permitidas';
  end if;

  v_path := u::text||'/'||p_trabajo::text||'/'||pg_catalog.gen_random_uuid()::text||'.'||v_ext;
  insert into public.virtual_entregas(
    trabajo_id,user_id,docente_id,colegio_id,nombre,size,path,estado,expires_at
  ) values (
    p_trabajo,u,v_work.docente_id,v_work.colegio_id,left(btrim(p_nombre),255),p_size,v_path,'pendiente',now()+interval '30 minutes'
  ) returning id into v_id;

  return jsonb_build_object('path',v_path,'entrega_id',v_id);
end;
$$;

create or replace function public.virtual_confirmar_entrega(p_entrega uuid,p_comentario text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  u uuid := (select auth.uid());
  v public.virtual_entregas%rowtype;
begin
  if u is null then raise exception 'Debes iniciar sesión'; end if;
  select * into v
  from public.virtual_entregas e
  where e.id = p_entrega and e.user_id = u
  for update;
  if not found or v.estado <> 'pendiente' or v.expires_at <= now() then
    raise exception 'La entrega pendiente no existe o venció';
  end if;
  if not exists (
    select 1 from storage.objects o
    where o.bucket_id = 'virtual-entregas' and o.name = v.path
  ) then
    raise exception 'No encontramos el archivo cargado; vuelve a intentarlo';
  end if;

  update public.virtual_entregas
  set estado = 'enviada',
      comentario = nullif(left(btrim(coalesce(p_comentario,'')),2000),''),
      expires_at = now()
  where id = p_entrega;
  return true;
end;
$$;

create or replace function public.virtual_cancelar_entrega(p_entrega uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  u uuid := (select auth.uid());
begin
  if u is null then raise exception 'Debes iniciar sesión'; end if;
  delete from public.virtual_entregas
  where id = p_entrega and user_id = u and estado = 'pendiente';
  if not found then raise exception 'No hay una entrega pendiente para cancelar'; end if;
end;
$$;

