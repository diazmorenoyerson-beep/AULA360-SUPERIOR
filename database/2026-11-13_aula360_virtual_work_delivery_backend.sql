create or replace function public.virtual_set_work_school()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_school bigint;
begin
  if new.docente_id is distinct from (select auth.uid()) then
    raise exception 'El responsable del trabajo debe ser el usuario autenticado';
  end if;
  select p.colegio_id into v_school
  from public.profiles p
  where p.id = (select auth.uid());
  if v_school is null then
    raise exception 'Tu perfil no tiene un colegio asociado';
  end if;
  new.colegio_id := v_school;
  return new;
end;
$$;

create trigger virtual_trabajos_set_school
before insert on public.virtual_trabajos
for each row execute function public.virtual_set_work_school();

create or replace function public.virtual_set_child_scope()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_owner uuid;
  v_school bigint;
begin
  select t.docente_id, t.colegio_id
    into v_owner, v_school
  from public.virtual_trabajos t
  where t.id = new.trabajo_id;
  if not found then
    raise exception 'El trabajo no existe o no está autorizado';
  end if;
  new.docente_id := v_owner;
  new.colegio_id := v_school;
  return new;
end;
$$;

create trigger virtual_trabajo_cursos_set_scope
before insert on public.virtual_trabajo_cursos
for each row execute function public.virtual_set_child_scope();

